"""Тексты ошибок и сообщений — по таблице «Ошибки» ТЗ v1.1.2.

Единый формат: код (латиницей) + статус HTTP + текст на русском.
Код показывается пользователю мелким шрифтом под сообщением.
T11 расширит файл текстами интерфейса; ошибки зафиксированы ТЗ и здесь.
"""
from __future__ import annotations

# Код → (текст по умолчанию, статус HTTP по умолчанию)
ERROR_TEXTS: dict[str, tuple[str, int]] = {
    "VALIDATION_ERROR": ("Проверьте выделенные поля", 422),
    "AUTH_REQUIRED": ("", 303),  # без сообщения, редирект на /login
    "AUTH_FAILED": ("Неверный логин или пароль", 401),
    "CSRF_FAILED": ("Страница устарела. Обновите её и повторите действие", 403),
    # FORBIDDEN — три случая, тексты различаются (ТЗ); текст по умолчанию — «роль»
    "FORBIDDEN": ("Это действие вам недоступно", 403),
    "FORBIDDEN_SELF_ACCEPT": ("Нельзя принять смену, которую вы сдали сами", 403),
    "FORBIDDEN_SELF_DEACTIVATE": (
        "Нельзя отключить собственную учётную запись", 403),
    "NOT_FOUND": ("Страница не найдена", 404),
    "NO_OPEN_SHIFT": ("Сначала откройте смену", 409),
    "SHIFT_NOT_EDITABLE": (
        "Этот вопрос сейчас нельзя изменить: смена сдана или вопрос в чужой смене", 409),
    "ISSUE_CLOSED": ("Вопрос уже закрыт", 409),
    "ALREADY_ACCEPTED": ("Смена уже принята: {name}, {time}", 409),
    "ACCOUNT_LIMIT": ("Достигнут лимит: 10 учётных записей на отель", 409),
    "DEMO_EXISTS": ("Демо-передача уже создана и ждёт приёма", 409),
    "INTERNAL_ERROR": (
        "Ошибка сервера. Запись не сохранена. Если ошибка повторяется, "
        "передайте смену на бумаге и внесите записи позже", 500),
}


def error_text(code: str, **params) -> str:
    text = ERROR_TEXTS[code][0]
    return text.format(**params) if params else text


def error_status(code: str) -> int:
    return ERROR_TEXTS[code][1]
