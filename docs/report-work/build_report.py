def _rpr(bold=False, size=None, color=None, italic=False, mono=False):
    r = OxmlElement("w:rPr")
    rf = OxmlElement("w:rFonts")
    name = "Consolas" if mono else "Calibri"
    rf.set(qn("w:ascii"), name)
    rf.set(qn("w:hAnsi"), name)
    rf.set(qn("w:cs"), name)
    r.append(rf)
    if bold:
        r.append(OxmlElement("w:b"))
        r.append(OxmlElement("w:bCs"))
    if italic:
        r.append(OxmlElement("w:i"))
    if size:
        sz = OxmlElement("w:sz")
        sz.set(qn("w:val"), str(int(size * 2)))
        szcs = OxmlElement("w:szCs")
        szcs.set(qn("w:val"), str(int(size * 2)))
        r.extend((sz, szcs))
    if color is not None:
        c = OxmlElement("w:color")
        c.set(qn("w:val"), "%02X%02X%02X" % (color[0], color[1], color[2]))
        r.append(c)
    return r


def add(key, pieces, size=None, space_before=None, space_after=None):
    """pieces: list of (text, {bold|italic|mono|color}) — один абзац."""
    p = doc.add_paragraph()
    if PPR.get(key) is not None:
        p._p.insert(0, copy.deepcopy(PPR[key]))
    if space_before is not None or space_after is not None:
        pf = p.paragraph_format
        if space_before is not None:
            pf.space_before = Pt(space_before)
        if space_after is not None:
            pf.space_after = Pt(space_after)
    for text, fmt in pieces:
        run = p.add_run(text)
        run._r.insert(0, _rpr(bold=fmt.get("bold", False),
                              size=size or fmt.get("size"),
                              color=fmt.get("color"),
                              italic=fmt.get("italic", False),
                              mono=fmt.get("mono", False)))
    return p


def plain(text, size=None, bold=False, italic=False, color=None,
          align=None, before=None, after=None, mono=False):
    p = doc.add_paragraph()
    if before is not None or after is not None:
        pf = p.paragraph_format
        if before is not None:
            pf.space_before = Pt(before)
        if after is not None:
            pf.space_after = Pt(after)
    run = p.add_run(text)
    run._r.insert(0, _rpr(bold=bold, size=size, italic=italic, color=color,
                          mono=mono))
    if align == "center":
        p.alignment = WD_ALIGN_PARAGRAPH.CENTER
    return p


def heading(text, page_break=False):
    p = doc.add_paragraph()
    p._p.insert(0, copy.deepcopy(HEAD_PPR))
    p.paragraph_format.space_before = Pt(16)
    p.paragraph_format.space_after = Pt(6)
    p.paragraph_format.page_break_before = page_break
    run = p.add_run(text)
    run._r.insert(0, copy.deepcopy(HEAD_RPR))
    return p


