def fig(name, caption, ratio=None):
    """Картинка по центру + подпись «Рис. N»; размер — по реальному файлу."""
    from PIL import Image
    w_px, h_px = Image.open(SHOTS / name).size
    ratio = h_px / w_px
    width = min(8.6 if ratio <= 1.15 else 7.4, 17.0 / ratio)
    p = doc.add_paragraph()
    p.alignment = WD_ALIGN_PARAGRAPH.CENTER
    p.paragraph_format.space_before = Pt(8)
    p.paragraph_format.space_after = Pt(2)
    p.paragraph_format.keep_with_next = True  # подпись не уезжает от рисунка
    run = p.add_run()
    run.add_picture(str(SHOTS / name), width=Cm(width))
    num = str(len(FIGS) + 1)
    FIGS.append((num, caption))
    plain(f"Рис. {num}. {caption}", size=8.5, color=GRAY, align="center",
          after=10)


